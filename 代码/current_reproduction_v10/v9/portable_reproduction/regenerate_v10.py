"""Audit immutable complete commands, regenerate v9 outputs, then v10 presentation."""
import os
for key in ('OMP_NUM_THREADS', 'MKL_NUM_THREADS', 'OPENBLAS_NUM_THREADS'):
    os.environ[key] = '1'
import argparse
from pathlib import Path
import subprocess
import sys
import time
from archive_tools import digest, read, write_new, verify_files
from portable_paths import install_guard
from run_trace_matrix_v9 import audit_matrix


def check_arrays(left, right):
    import numpy as np
    with np.load(left, allow_pickle=False) as a, np.load(right, allow_pickle=False) as b:
        assert set(a.files) == set(b.files), (left, 'array keys')
        for key in a.files:
            assert a[key].dtype == b[key].dtype and a[key].shape == b[key].shape, (left, key)
            assert np.array_equal(a[key], b[key], equal_nan=np.issubdtype(a[key].dtype, np.inexact)), (left, key)


def compare_products(reference, output, *, names=None):
    compared = []
    json_names = {'scientific_values.json', 'planning_cost_data.json',
        'extension_efficiency_data.json', 'figure9_v9_data.json',
        'extension_presentation_receipt.json', 'metrics.json'}
    paths = [reference / name for name in names] if names is not None else sorted(reference.iterdir())
    for path in paths:
        if not path.is_file():
            continue
        target = output / path.name
        if path.suffix in ('.tex', '.png', '.csv') or path.name in json_names or (names and path.suffix == '.json'):
            assert target.is_file() and digest(path) == digest(target), 'Regenerated bytes differ: ' + path.name
            mode = 'exact_bytes'
        elif path.suffix == '.npz':
            check_arrays(path, target)
            mode = 'exact_array_keys_types_shapes_values'
        elif path.suffix in ('.pdf', '.svg'):
            assert target.is_file() and target.stat().st_size > 0, 'Missing regenerated graphic: ' + path.name
            mode = 'regenerated_with_exact_data_and_png'
        else:
            continue
        compared.append(dict(file=path.name, comparison=mode, sha256=digest(target)))
    return compared


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--workspace', type=Path, required=True)
    parser.add_argument('--jobs', type=int, default=4)
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    root = args.workspace.resolve()
    v9, here = root / 'v9', root / 'v9/portable_reproduction'
    out = (args.output or root / 'regenerated_v10').resolve()
    if not out.is_relative_to(root) or out.exists():
        raise ValueError('Choose a new output directory inside the extracted workspace.')
    guard, started = install_guard(root), time.perf_counter()
    manifest = read(root / 'SCIENTIFIC_MANIFEST_V10.json')
    source = read(root / 'SOURCE_PROVENANCE_V10.json')
    verify_files(root, manifest['files'])
    verify_files(root, source['immutable_source_files'])
    print('Verified immutable source evidence:', len(source['immutable_source_files']), flush=True)
    out.mkdir(parents=True)
    audits = audit_matrix(root, out, args.jobs)
    figures = out / 'paper'
    figures.mkdir()
    guards = {}

    def run_step(name, script, arguments):
        with (out / 'logs' / (name + '.log')).open('x', encoding='utf-8') as stream:
            subprocess.run([sys.executable, '-B', '-X', 'utf8', str(here / 'guarded_python.py'),
                '--workspace', str(root), '--guard-receipt', str(out / (name + '_guard.json')),
                '--', str(script), *arguments], cwd=root, stdout=stream,
                stderr=subprocess.STDOUT, check=True)
        guards[name] = read(out / (name + '_guard.json'))
        assert guards[name]['guard_active'] and not guards[name]['blocked_original_accesses']

    common = ['--root', str(v9), '--base', str(root), '--output', str(figures)]
    for name, script in (('generator', 'generate_paper_v9.py'),
                         ('figure9', 'plot_extension_clarity_v9.py'),
                         ('formatter', 'format_extension_results_v9.py')):
        run_step(name, v9 / 'src' / script, common)
    compared_v9 = compare_products(v9 / 'paper_presentation_final', figures)
    prior = read(v9 / 'paper_presentation_final/v9_generation_receipt.json')
    regenerated = read(figures / 'v9_generation_receipt.json')
    for key in ('comparison_sha256', 'generalization_sha256', 'runs', 'generalization_runs',
                'successful_runs', 'generator_sha256', 'source_traces'):
        assert prior[key] == regenerated[key], key
    presentation = read(root / 'v10/presentation_manifest.json')
    values = dict(workspace=str(root), v9=str(v9), figures=str(figures))
    for step in presentation['steps']:
        script = (root / step['script']).resolve()
        assert script.is_relative_to(root) and script.is_file()
        run_step(step['name'], script, [a.format(**values) for a in step['arguments']])
    reference = root / presentation['reference_directory']
    compared_v10 = compare_products(reference, figures, names=presentation['compare_files'])
    verify_files(root, manifest['files'])
    verify_files(root, source['immutable_source_files'])
    receipt = dict(status='passed', expected_cells=66, audited_cells=len(audits),
        full_trace_cells=sum(r['trace_present'] for r in audits),
        failed_planning_cells_retained=sum(not r['trace_present'] for r in audits),
        comparison_sha256=digest(v9 / 'canonical/final_comparison.json'),
        generalization_sha256=digest(v9 / 'boundary_refinement/generalization_summary.json'),
        audited_sources_unchanged=True, source_files_reverified=len(source['immutable_source_files']),
        complete_manifest_files_reverified=len(manifest['files']),
        all_worker_original_directory_guards_passed=True, step_guards=guards,
        coordinator_guard=guard, legacy_generated_products=compared_v9,
        presentation_generated_products=compared_v10, presentation_only=True,
        no_training_or_rollouts=True,
        pdf_scope='PDF/SVG regenerated from exact data; timestamps and identifiers may differ. PNG and scientific arrays exact.',
        wall_s=time.perf_counter() - started)
    write_new(out / 'REGENERATION_RECEIPT_V10.json', receipt)
    print('PASSED: all 66 cells audited; source evidence unchanged; scientific artifacts and presentation regenerated.', flush=True)


if __name__ == '__main__':
    main()
